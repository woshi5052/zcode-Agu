def is_trading_day(d: date | str = None) -> bool:
    """判断是否为交易日"""
    if d is None:
        d = date.today()
    if isinstance(d, str):
        d = date.fromisoformat(d)

    # 周末
    if d.weekday() >= 5:
        return False

    # 节假日
    if d.isoformat() in _HOLIDAYS:
        return False

    return True


def next_trading_day(d: date | str = None) -> date:
    """返回下一个交易日"""
    if d is None:
        d = date.today()
    if isinstance(d, str):
        d = date.fromisoformat(d)

    d = d + timedelta(days=1)
    while not is_trading_day(d):
        d = d + timedelta(days=1)
    return d


def prev_trading_day(d: date | str = None) -> date:
    """返回上一个交易日"""
    if d is None:
        d = date.today()
    if isinstance(d, str):
        d = date.fromisoformat(d)

    d = d - timedelta(days=1)
    while not is_trading_day(d):
        d = d - timedelta(days=1)
    return d


def trading_days_in_range(start: str, end: str) -> list[date]:
    """返回区间内所有交易日"""
    s = date.fromisoformat(start)
    e = date.fromisoformat(end)
    days = []
    d = s
    while d <= e:
        if is_trading_day(d):
            days.append(d)
        d += timedelta(days=1)
    return days
